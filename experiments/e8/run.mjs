// E8 held-out evaluation (see PROTOCOL.md): default elevation amplitude.
// Usage: npm run build:cli && node experiments/e8/run.mjs <outDir>
// Seeds: SEEDS[100..199] of experiments/e1/cases.mjs. Writes cases.csv, SUMMARY.json, SUMMARY.md (deterministic: no timestamps, no timings).
import { writeFileSync, mkdirSync } from 'node:fs';
import { SEEDS } from '../e1/cases.mjs';
const core = await import(new URL('../../cli-dist/core.js', import.meta.url));
const val = await import(new URL('../../cli-dist/validate.js', import.meta.url));
const outDir = process.argv[2];
if (!outDir) { console.error('usage: run.mjs <outDir>'); process.exit(2); }
const D = core.DEFAULTS;
if (D.height !== 20 || D.size !== 2 || D.autoJoin !== 'tangent') throw new Error('DEFAULTS are not the configuration of PROTOCOL.md');
const seeds = SEEDS.slice(100, 200);
const Z = 1.959963984540054, r6 = x => Math.round(x * 1e6) / 1e6;
function wilson(k, n) { const p = k / n, d = 1 + Z * Z / n, c = (p + Z * Z / (2 * n)) / d, h = Z * Math.sqrt(p * (1 - p) / n + Z * Z / (4 * n * n)) / d; return { k, n, p: r6(p), lo: r6(Math.max(0, c - h)), hi: r6(Math.min(1, c + h)) }; }
const sorted = a => [...a].sort((x, y) => x - y);
const median = a => { const s = sorted(a), m = s.length >> 1; return r6(s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2); };
const p95 = a => r6(sorted(a)[Math.floor(0.95 * a.length)]);

function evaluate(label, height) { // height === undefined: the default path generateTrack({ seed })
  const rows = [];
  for (const seed of seeds) {
    let t;
    try { t = height === undefined ? core.generateTrack({ seed }) : core.generateTrack({ seed, height }); } catch (e) { rows.push({ label, seed, generated: 0 }); continue; }
    const r = val.validateTrack(t);
    rows.push({ label, seed, generated: 1, height: t.params.height, ok: r.ok ? 1 : 0, maxSlopeWarn: r.violations.some(v => v.code === 'MAX_SLOPE') ? 1 : 0,
      maxAbsSlope: r.checks.find(c => c.id === 'max-slope').stats.maxAbsSlope, range: t.bounds.maxY - t.bounds.minY });
  }
  const g = rows.filter(x => x.generated);
  return { label, rows, summary: { generated: wilson(g.length, rows.length), maxSlopeRate: wilson(g.filter(x => x.maxSlopeWarn).length, g.length),
    okRate: wilson(g.filter(x => x.ok).length, g.length),
    elevationRange: { median: median(g.map(x => x.range)), min: r6(Math.min(...g.map(x => x.range))), max: r6(Math.max(...g.map(x => x.range))) },
    maxSlope: { median: median(g.map(x => x.maxAbsSlope)), p95: p95(g.map(x => x.maxAbsSlope)), max: r6(Math.max(...g.map(x => x.maxAbsSlope))) } } };
}
const dflt = evaluate('default (DEFAULTS, height 20)', undefined);
const ctrl = evaluate('control (height 80)', 80);
const S = dflt.summary, C = ctrl.summary;
const preds = [
  { id: 'P1', text: 'MAX_SLOPE rate at default <= 5% (<= 5 of 100)', value: S.maxSlopeRate.k, pass: S.maxSlopeRate.k <= 5 && S.maxSlopeRate.n === 100 },
  { id: 'P2', text: 'ok 100/100 at height 20 and at height 80', value: [S.okRate.k, C.okRate.k], pass: S.okRate.k === 100 && C.okRate.k === 100 },
  { id: 'P3', text: 'median elevation range >= 40 and minimum >= 36 at height 20', value: [S.elevationRange.median, S.elevationRange.min], pass: S.elevationRange.median >= 40 && S.elevationRange.min >= 36 },
  { id: 'P4', text: 'all tracks generated at both heights', value: [S.generated.k, C.generated.k], pass: S.generated.k === 100 && C.generated.k === 100 },
  { id: 'P5', text: 'control MAX_SLOPE rate at height 80 >= 95%', value: C.maxSlopeRate.p, pass: C.maxSlopeRate.p >= 0.95 },
];
const summary = { protocol: 'experiments/e8/PROTOCOL.md', seedSet: 'SEEDS[100..199]', seeds, defaults: { height: D.height, size: D.size, autoJoin: D.autoJoin },
  validator: { maxSlope: val.DEFAULT_VALIDATE_OPTIONS.maxSlope }, default: S, control: C, predictions: preds };
mkdirSync(outDir, { recursive: true });
writeFileSync(`${outDir}/cases.csv`, ['label,seed,generated,height,ok,maxSlopeWarn,maxAbsSlope,elevationRange',
  ...[...dflt.rows, ...ctrl.rows].map(x => [JSON.stringify(x.label), x.seed, x.generated, x.height ?? '', x.ok ?? '', x.maxSlopeWarn ?? '', x.generated ? x.maxAbsSlope.toFixed(6) : '', x.generated ? x.range.toFixed(6) : ''].join(','))].join('\n') + '\n');
writeFileSync(`${outDir}/SUMMARY.json`, JSON.stringify(summary, null, 2) + '\n');
const w = x => `${x.k}/${x.n} = ${(100 * x.p).toFixed(1)}% (Wilson 95%: ${(100 * x.lo).toFixed(1)}% to ${(100 * x.hi).toFixed(1)}%)`;
const md = ['# E8 held-out results (generated by run.mjs; no prose interpretation here)', '', `Seeds: SEEDS[100..199] (${seeds.length}). Validator maxSlope ${summary.validator.maxSlope}. DEFAULTS: height ${D.height}, size ${D.size}, autoJoin ${D.autoJoin}.`, '',
  '| measure | default (height 20) | control (height 80) |', '|---|---|---|',
  `| generated | ${w(S.generated)} | ${w(C.generated)} |`, `| MAX_SLOPE | ${w(S.maxSlopeRate)} | ${w(C.maxSlopeRate)} |`, `| ok (errors only) | ${w(S.okRate)} | ${w(C.okRate)} |`,
  `| elevation range median / min / max | ${S.elevationRange.median} / ${S.elevationRange.min} / ${S.elevationRange.max} | ${C.elevationRange.median} / ${C.elevationRange.min} / ${C.elevationRange.max} |`,
  `| max slope median / p95 / max | ${S.maxSlope.median} / ${S.maxSlope.p95} / ${S.maxSlope.max} | ${C.maxSlope.median} / ${C.maxSlope.p95} / ${C.maxSlope.max} |`, '',
  '## Predictions (PROTOCOL.md section 5)', '', ...preds.map(p => `- ${p.id} ${p.pass ? 'HELD' : 'FAILED'}: ${p.text}; observed ${JSON.stringify(p.value)}`), ''];
writeFileSync(`${outDir}/SUMMARY.md`, md.join('\n'));
